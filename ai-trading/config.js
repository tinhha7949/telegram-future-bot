function parseConfig(text) {
  if (typeof text !== "string") throw new Error("CONFIG_MISSING");
  const out = {};
  for (const [i, source] of text.split(/\r?\n/).entries()) {
    const line = source.replace(/\s+#.*$/, "").trim();
    if (!line || line.startsWith("#")) continue;
    const match = /^([A-Z][A-Z0-9_]*):\s*(.*?)\s*$/.exec(line);
    if (!match) throw new Error("CONFIG_INVALID_LINE_" + (i + 1));
    const [, key, raw] = match;
    if (!KEYS.includes(key) || Object.hasOwn(out, key))
      throw new Error("CONFIG_UNEXPECTED_OR_DUPLICATE_" + key);
    let value;
    if (raw.startsWith('"') || raw.startsWith("[")) {
      try { value = JSON.parse(raw); }
      catch { throw new Error("CONFIG_INVALID_VALUE_" + key); }
    } else if (/^(?:\d+(?:\.\d+)?|\.\d+)$/.test(raw)) {
      value = Number(raw);
    } else {
      throw new Error("CONFIG_INVALID_VALUE_" + key);
    }
    out[key] = value;
  }
  for (const key of KEYS)
    if (!Object.hasOwn(out, key)) throw new Error("CONFIG_MISSING_" + key);
  for (const [key, v] of Object.entries(out)) {
    if (["TIMEFRAME", "TP_BATCHES"].includes(key)) continue;
    if (!Number.isFinite(v) || v <= 0)
      throw new Error("CONFIG_INVALID_NUMBER_" + key);
  }
  if (out.TIMEFRAME !== "4h" ||
      !Array.isArray(out.TP_BATCHES) ||
      out.TP_BATCHES.length !== 2 ||
      out.TP_BATCHES.some(v => !Number.isSafeInteger(v) || v <= 0) ||
      out.RISK_PER_TRADE > out.MAX_DAILY_RISK ||
      out.MAX_DAILY_RISK >= 1 ||
      out.MAX_DRAWDOWN_CIRCUIT >= 1 ||
      out.WAIT_MIN_RATIO >= 1 ||
      out.CONF_LOW >= out.CONF_HIGH ||
      out.CONF_HIGH > 1 ||
      out.HIGH_VOL_PERCENTILE >= 1 ||
      out.HISTORY_FETCH_CANDLES < out.VOL_90D_RETURNS + 1 ||
      out.N_CANDLES > out.HISTORY_FETCH_CANDLES ||
      out.AI7_ACTIVATION_SAMPLES < out.COLD_START_SAMPLES ||
      out.FALLBACK_TP2_R < out.MIN_RR ||
      out.RETENTION_TRIGGER_RATIO >= 1 ||
      out.RETENTION_TARGET_RATIO >= out.RETENTION_TRIGGER_RATIO ||
      out.TIMEFRAME !== `${out.BAR_HOURS}h` ||
      out.MOMENTUM_SHORT_RETURNS >= out.VOL_20D_RETURNS ||
      out.STRUCTURE_LOOKBACK_BARS > out.N_CANDLES ||
      out.REGIME_CONF_BASE + out.REGIME_CONF_MOMENTUM_WEIGHT + out.REGIME_CONF_VOL_WEIGHT > 1 ||
      out.REGIME_CONF_VOL_MIDPOINT >= 1 ||
      out.BREAKOUT_MIN_VOLUME_RATIO < 1 ||
      out.FILL_DEPTH_FLOOR >= 1 ||
      out.CALIBRATION_MIN_SAMPLES > out.TRAIN_MAX_OPPORTUNITIES ||
      out.MAE_PERCENTILE >= 1 || out.MFE_TP1_PERCENTILE >= 1 ||
      out.MFE_TP2_PERCENTILE >= 1 ||
      out.MFE_TP1_PERCENTILE > out.MFE_TP2_PERCENTILE ||
      out.INITIAL_OI_LOG_LOWER_MAGNITUDE >= 1 ||
      out.TRAIN_SPLIT_RATIO >= out.VALIDATION_SPLIT_RATIO ||
      out.VALIDATION_SPLIT_RATIO >= 1)
    throw new Error("CONFIG_CROSS_FIELD_INVARIANT");
  for (const key of ["N_CANDLES", "TIMEOUT_BARS", "COLD_START_SAMPLES",
      "AI7_ACTIVATION_SAMPLES", "HISTORY_FETCH_CANDLES", "ATR_BARS",
      "VOL_20D_RETURNS", "VOL_90D_RETURNS", "BAR_HOURS",
      "MOMENTUM_SHORT_RETURNS", "STRUCTURE_SWING_RADIUS",
      "STRUCTURE_LOOKBACK_BARS", "STRUCTURE_FALLBACK_BARS",
      "VOLUME_LOOKBACK_BARS", "BREAKOUT_RANGE_BARS", "VWAP_LOOKBACK_BARS",
      "SCAN_INTERVAL_MS", "SCAN_BATCH_SIZE", "SCAN_PROGRESS_EVERY_SYMBOLS",
      "PROTECTION_INTERVAL_MS", "BOOKKEEPING_INTERVAL_MS",
      "NOTIFICATION_INTERVAL_MS", "CLOCK_SYNC_INTERVAL_MS",
      "LEARNING_INTERVAL_HOURS", "COMMAND_POLL_INTERVAL_MS",
      "COMMAND_LONG_POLL_SECONDS", "COMMAND_HTTP_TIMEOUT_MS",
      "MARKET_OI_CACHE_MS", "MARKET_DEPTH_CACHE_MS", "MARKET_DEPTH_LEVELS",
      "MARKET_OI_HISTORY_POINTS", "MAIN_IDLE_SLEEP_MS", "TELEGRAM_HTTP_TIMEOUT_MS",
      "CALIBRATION_MIN_SAMPLES", "RECENT_LABELS_LIMIT",
      "TRACK_RECORD_CACHE_MS", "OFFLINE_WORKER_MAX_OLD_GEN_MB",
      "OFFLINE_TRAIN_TIMEOUT_MS", "RETENTION_CLEANUP_GUARD_ITERATIONS",
      "MONGO_CONNECT_TIMEOUT_MS", "MONGO_SERVER_SELECTION_TIMEOUT_MS",
      "MONGO_SOCKET_TIMEOUT_MS", "MONGO_MAX_POOL_SIZE",
      "TELEGRAM_MAX_MESSAGE_CHARS", "PID_LOCK_ATTEMPTS",
      "PID_HASH_HEX_CHARS", "SESSION_REPORT_WINDOW_HOURS",
      "SESSION_REPORT_MAX_TRADES", "SESSION_REPORT_MAX_WAIT_RECORDS"]) {
    if (!Number.isSafeInteger(out[key]))
      throw new Error("CONFIG_NOT_INTEGER_" + key);
  }
  out.TP_BATCHES = Object.freeze(out.TP_BATCHES);
  return Object.freeze(out);
}
const CONFIG = parseConfig(fs.readFileSync(path.join(__dirname, "..", "CONFIG.yaml"), "utf8"));
module.exports = { CONFIG, parseConfig };
